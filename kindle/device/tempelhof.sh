#!/bin/sh
# ============================================================
# Tempelhof Field dashboard — runs on a jailbroken Kindle
# Paperwhite 3 (installed to /mnt/us/tempelhof/bin/).
#
# Every minute: wake on the RTC alarm, look up the next
# open/close event in schedule.txt, paste the countdown image
# with eips, and suspend to RAM again. No Wi-Fi is used.
#
# Press the power button (or plug in USB) to exit: the device
# then wakes before its alarm, which the loop detects.
#
#   tempelhof.sh start [TEST_MINUTES]  run the dashboard (TEST_MINUTES > 0 stops after that long)
#   tempelhof.sh once [EPOCH]          draw one frame, no suspend (for testing)
#   tempelhof.sh plan [EPOCH]          print what would be drawn, draw nothing
# ============================================================

DIR=${TEMPELHOF_DIR:-/mnt/us/tempelhof}
LOG=$DIR/tempelhof.log
PIDFILE=/tmp/tempelhof.pid
RTC=${TEMPELHOF_RTC:-/sys/class/rtc/rtc1/wakealarm}
EIPS=${EIPS:-/usr/sbin/eips}
FULL_EVERY=15   # full refresh every N minutes to clear e-ink ghosting
LOW_BATTERY=15  # show "Battery low" at or below this %
# Europe/Berlin as a POSIX rule: the Kindle's own zone setting is unreliable.
BERLIN_TZ='CET-1CEST,M3.5.0,M10.5.0/3'

. "$DIR/layout.env"  # CD_X CD_Y DATE_X DATE_Y BAT_X BAT_Y (generated by kindle/build.mjs)

log() {
  echo "$(date -u '+%Y-%m-%d %H:%M:%S') $*" >> "$LOG"
}

battery() {
  gasgauge-info -c 2>/dev/null | tr -dc '0-9'
}

# "<event-epoch> <background-key> <minutes-left, rounded up>" for epoch $1
lookup() {
  awk -v now="$1" '
    $1 > now { print $1, $3, int(($1 - now + 59) / 60); found = 1; exit }
    END { if (!found) exit 1 }
  ' "$DIR/schedule.txt"
}

berlin_day() {  # Berlin calendar date of epoch $1, e.g. 2026-11-23
  TZ=$BERLIN_TZ date -d "@$1" +%Y-%m-%d 2>/dev/null || TZ=$BERLIN_TZ date -r "$1" +%Y-%m-%d
}

draw() {  # $1 background key, $2 minutes left, $3 = 1 for a full redraw, $4 date to paste (or empty)
  if [ "$3" = 1 ]; then
    "$EIPS" -f -g "$DIR/img/bg/$1.png" >/dev/null 2>&1
  fi
  "$EIPS" -g "$DIR/img/cd/$2.png" -x "$CD_X" -y "$CD_Y" >/dev/null 2>&1
  if [ -n "$4" ]; then
    "$EIPS" -g "$DIR/img/date/$4.png" -x "$DATE_X" -y "$DATE_Y" >/dev/null 2>&1
  fi
}

# Keep the Kindle UI from drawing over the dashboard. framework stays
# up (it owns the power button); lab126_gui can be relaunched after a
# wake, so this runs every loop.
take_screen() {
  lipc-set-prop com.lab126.powerd preventScreenSaver 1 >/dev/null 2>&1
  initctl stop lab126_gui >/dev/null 2>&1
  initctl stop webreader >/dev/null 2>&1
}

restore_ui() {
  echo 0 > "$RTC" 2>/dev/null
  lipc-set-prop com.lab126.powerd preventScreenSaver 0 >/dev/null 2>&1
  if [ "$WIFI_WAS" != 0 ]; then
    lipc-set-prop com.lab126.wifid enable 1 >/dev/null 2>&1
  fi
  initctl start lab126_gui >/dev/null 2>&1
  rm -f "$PIDFILE"
}

run() {
  test_minutes=${1:-0}

  if [ -f "$PIDFILE" ] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; then
    log "already running (pid $(cat "$PIDFILE"))"
    exit 0
  fi
  echo $$ > "$PIDFILE"

  # Rotate the log before it grows large (it lives on the FAT user partition).
  if [ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 200000 ]; then
    mv "$LOG" "$LOG.1"
  fi
  log "start: test_minutes=$test_minutes battery=$(battery)% rtc=$RTC"

  # Let the scriptlet launcher hand the screen back to the library first.
  sleep 4

  WIFI_WAS=$(lipc-get-prop com.lab126.wifid enable 2>/dev/null)
  lipc-set-prop com.lab126.wifid enable 0 >/dev/null 2>&1
  take_screen
  sleep 3

  trap 'log "stopped by signal"; restore_ui; exit 0' TERM INT HUP

  started=$(date +%s)
  last_bg=""
  last_day=""
  since_full=$FULL_EVERY
  last_battery_log=0

  while :; do
    now=$(date +%s)
    if [ "$test_minutes" -gt 0 ] && [ $((now - started)) -ge $((test_minutes * 60)) ]; then
      log "test run finished after $test_minutes min"
      break
    fi

    set -- $(lookup "$now")
    if [ $# -ne 3 ]; then
      log "schedule exhausted: rebuild and reinstall (npm run kindle:build)"
      break
    fi
    bg=$2
    minutes=$3

    take_screen
    full=0
    if [ "$bg" != "$last_bg" ] || [ "$since_full" -ge "$FULL_EVERY" ]; then
      full=1
      last_bg=$bg
      since_full=0
    fi
    # The date is redrawn after a full redraw (which clears it) or at midnight.
    day=$(berlin_day "$now")
    date_to_draw=""
    if [ "$full" = 1 ] || [ "$day" != "$last_day" ]; then
      date_to_draw=$day
      last_day=$day
    fi
    draw "$bg" "$minutes" "$full" "$date_to_draw"
    since_full=$((since_full + 1))

    level=$(battery)
    if [ "$full" = 1 ] && [ -n "$level" ] && [ "$level" -le "$LOW_BATTERY" ]; then
      "$EIPS" -g "$DIR/img/battery-low.png" -x "$BAT_X" -y "$BAT_Y" >/dev/null 2>&1
    fi
    if [ $((now - last_battery_log)) -ge 3600 ]; then
      log "battery ${level}% (showing $bg, $minutes min left)"
      last_battery_log=$now
    fi

    # Give the e-ink update time to finish before the CPU stops.
    if [ "$full" = 1 ]; then sleep 2; else sleep 1; fi

    # Suspend until the next minute boundary.
    now=$(date +%s)
    secs=$((60 - now % 60))
    echo 0 > "$RTC"
    echo "+$secs" > "$RTC"
    echo mem > /sys/power/state 2>/dev/null
    rc=$?
    if [ "$rc" -ne 0 ]; then
      log "suspend failed (rc=$rc): staying awake for ${secs}s"
      sleep "$secs"
      continue
    fi

    # The alarm clears itself when it fires. Still pending means
    # something else woke us: the power button or a USB cable.
    if [ -n "$(cat "$RTC" 2>/dev/null)" ]; then
      log "woke before the alarm (power button or USB): exiting"
      break
    fi
  done

  restore_ui
  log "exit: battery=$(battery)%"
}

case "$1" in
  start)
    run "${2:-0}"
    ;;
  once|plan)
    at=${2:-$(date +%s)}
    set -- "$1" $(lookup "$at")
    if [ $# -ne 4 ]; then
      echo "no event after $at in $DIR/schedule.txt" >&2
      exit 1
    fi
    day=$(berlin_day "$at")
    echo "at $at: next event $2, background $3, $4 min left, date $day; countdown at -x $CD_X -y $CD_Y"
    [ "$1" = once ] && draw "$3" "$4" 1 "$day"
    ;;
  *)
    echo "usage: $0 start [TEST_MINUTES] | once [EPOCH] | plan [EPOCH]" >&2
    exit 2
    ;;
esac
